def head(path, txt, cls, obj):
    """Write an OpenFOAM dictionary with the standard header."""
    with open(path, "w") as fh:
        fh.write("FoamFile\n{\n    version 2.0;\n    format ascii;\n"
                 f"    class {cls};\n    object {obj};\n}}\n\n")
        fh.write(txt)


def resample_closed(x, yu, yl, n):
    """Airfoil as one closed loop of n points, TE -> upper -> LE -> lower -> TE.

    S1223's trailing edge is cusped-thin.  A perfectly sharp TE makes the
    O-grid's outward normals collapse there, so the TE is opened to a small
    blunt face.  The SAME blunt face is applied to every variant, so it cannot
    bias the comparison.
    """
    # t/c; ~0.74 mm at 93 mm chord.  Bluntness is what keeps the marched
    # normals from the two surfaces crossing just ahead of the cusp.
    te_half = 0.008
    yu = yu.copy()
    yl = yl.copy()
    # taper the blunting in over the last 15% chord so the surface stays smooth
    w = np.clip((x - 0.85) / 0.15, 0.0, 1.0)
    yu += w * te_half
    yl -= w * te_half
    up = np.stack([x, yu], axis=1)[::-1]     # TE -> LE
    lo = np.stack([x, yl], axis=1)[1:]       # LE -> TE
    # blockMesh hex ordering: with the block's local x along the loop and
    # local y radially outward, the loop must run COUNTER-CLOCKWISE for the
    # block to come out right-handed.  Emitting it clockwise makes blockMesh
    # reject every block as "inside-out" (verified 2026-08-16).
    loop = np.vstack([up, lo])
    # arc-length resample to n points so cells are evenly sized around the loop
    d = np.r_[0.0, np.cumsum(np.linalg.norm(np.diff(loop, axis=0), axis=1))]
    s = np.linspace(0.0, d[-1], n, endpoint=False)
    return np.stack([np.interp(s, d, loop[:, 0]),
                     np.interp(s, d, loop[:, 1])], axis=1)


def build_rings(loop, n_rad, normal_smooth=160, blend_pow=1.25,
                untangle_iters=400):
    """Return n_rad+1 nested rings from the aerofoil out to the far field.

    A one-block O-grid cannot be used here.  blockMesh interpolates linearly
    between a block's inner and outer edges, and straight lines from a thin,
    strongly cambered section to a circle CROSS near the trailing edge -- 634
    negative-volume cells and skewness 5866 when tried (2026-08-16).

    Plain Laplacian relaxation of an initial blend does not fix it either: it
    equalises radial spacing, so the boundary-layer clustering washes out and
    the near-wall rings tangle (blockMesh then reports "inward-pointing
    faces", and the layer grading comes out below 1).

    What works is HYPERBOLIC MARCHING with a blend to the far field:

      * near the wall each ring is the previous ring pushed out along its own
        smoothed outward normal, which keeps rings parallel to the surface and
        preserves the geometric radial spacing exactly;
      * as the rings move out they are progressively blended toward the
        far-field circle, so by the outer boundary the grid is clean and
        circular regardless of what the aerofoil did.

    Normals are smoothed circumferentially before marching; that is what stops
    concave stretches (the S1223 lower surface) from folding the offset.
    """
    n = len(loop)
    cen = loop.mean(axis=0)
    # geometric radial distribution, first cell FIRST_CELL (in chords)
    t0 = FIRST_CELL / CHORD_M / R_FAR
    lo, hi = 1.0001, 1.5
    for _ in range(200):
        r = (lo + hi) / 2.0
        if t0 * (r ** n_rad - 1.0) / (r - 1.0) < 1.0:
            lo = r
        else:
            hi = r
    t = np.r_[0.0, np.cumsum(t0 * hi ** np.arange(n_rad))]
    t = np.clip(t / t[-1], 0.0, 1.0)

    def outward_normals(ring):
        """Smoothed outward unit normals of a CCW ring."""
        nxt = np.roll(ring, -1, axis=0)
        prv = np.roll(ring, 1, axis=0)
        tan = nxt - prv
        nrm = np.stack([tan[:, 1], -tan[:, 0]], axis=1)   # CCW -> outward
        for _ in range(normal_smooth):
            nrm = (np.roll(nrm, 1, axis=0) + 2.0 * nrm
                   + np.roll(nrm, -1, axis=0)) / 4.0
        ln = np.linalg.norm(nrm, axis=1, keepdims=True)
        return nrm / np.maximum(ln, 1e-15)

    rings = np.empty((n_rad + 1, n, 2))
    rings[0] = loop
    for j in range(n_rad):
        step = (t[j + 1] - t[j]) * R_FAR
        marched = rings[j] + outward_normals(rings[j]) * step
        # Project the MARCHED ring onto the circle along its own rays.  Using
        # a fixed arclength->angle map instead makes the target's point
        # correspondence disagree with the marched shape, which inverted ~7100
        # of 48000 quads; ray-projecting the marched ring drops that to ~40.
        d = marched - cen
        rad = np.linalg.norm(d, axis=1, keepdims=True)
        target = cen + (t[j + 1] * R_FAR) * (d / np.maximum(rad, 1e-15))
        w = t[j + 1] ** blend_pow
        rings[j + 1] = (1.0 - w) * marched + w * target

    def quad_areas(rr):
        a_, b_ = rr[:-1], rr[1:]
        a2_, b2_ = np.roll(a_, -1, axis=1), np.roll(b_, -1, axis=1)
        return 0.5 * (
            (a_[..., 0] * b_[..., 1] - b_[..., 0] * a_[..., 1])
            + (b_[..., 0] * b2_[..., 1] - b2_[..., 0] * b_[..., 1])
            + (b2_[..., 0] * a2_[..., 1] - a2_[..., 0] * b2_[..., 1])
            + (a2_[..., 0] * a_[..., 1] - a_[..., 0] * a2_[..., 1]))

    # Local untangling: relax only the points touching an inverted quad.  A
    # global smoothing pass would flatten the boundary-layer clustering, so the
    # repair is kept strictly local and stops as soon as the grid is clean.
    # This is what makes the generator work for every aerofoil variant instead
    # of only the one the parameters were tuned on.
    for _ in range(untangle_iters):
        bad = quad_areas(rings) <= 0.0
        if not bad.any():
            break
        touch = np.zeros(rings.shape[:2], dtype=bool)
        jj, kk = np.where(bad)
        for dj in (0, 1):
            for dk in (0, 1):
                touch[np.clip(jj + dj, 0, len(rings) - 1),
                      (kk + dk) % rings.shape[1]] = True
        touch[0] = False          # never move the aerofoil surface
        touch[-1] = False         # never move the far field
        lap = 0.25 * (np.roll(rings, 1, axis=1) + np.roll(rings, -1, axis=1)
                      + np.r_[rings[:1], rings[:-1]]
                      + np.r_[rings[1:], rings[-1:]])
        rings = np.where(touch[..., None], 0.5 * rings + 0.5 * lap, rings)

    # Self-check: every quad between consecutive rings must stay positively
    # oriented.  blockMesh would otherwise reject the block as "inside-out"
    # with a tiny negative volume, which is slow to diagnose from its message.
    a, b = rings[:-1], rings[1:]
    a2, b2 = np.roll(a, -1, axis=1), np.roll(b, -1, axis=1)
    area = 0.5 * ((a[..., 0] * b[..., 1] - b[..., 0] * a[..., 1])
                  + (b[..., 0] * b2[..., 1] - b2[..., 0] * b[..., 1])
                  + (b2[..., 0] * a2[..., 1] - a2[..., 0] * b2[..., 1])
                  + (a2[..., 0] * a[..., 1] - a[..., 0] * a2[..., 1]))
    if (area <= 0).any():
        raise RuntimeError(
            f"{int((area <= 0).sum())} of {area.size} grid quads are inverted; "
            "the O-grid would be rejected by blockMesh")
    return rings


def write_blockmesh(case, loop):
    """O-grid emitted as nested block layers between pre-smoothed rings.

    Each layer is thin enough that blockMesh's linear interpolation inside it
    cannot fold, while the shape of every layer boundary comes from
    build_rings() -- so the grid follows the smoothed elliptic solution rather
    than a straight blend from aerofoil to circle.
    """
    n = len(loop)
    q = n // N_CBLK
    cpl = N_RAD // N_LAYER
    rings = build_rings(loop, N_RAD)
    lev = [rings[L * cpl] for L in range(N_LAYER)] + [rings[N_RAD]]
    nlv = len(lev)

    def vid(level, k, z):
        return z * (nlv * n) + level * n + (k % n)

    verts = []
    for z, zc in enumerate((0.0, Z_THICK)):
        for level in range(nlv):
            for pt in lev[level]:
                verts.append((pt[0], pt[1], zc))
        del z
    vtxt = "\n".join(f"    ({v[0]:.8f} {v[1]:.8f} {v[2]:.8f})" for v in verts)

    # radial expansion inside each layer, taken from the ring spacing actually
    # generated, so the boundary-layer clustering survives the layer split
    def layer_ratio(L):
        a, b = L * cpl, (L + 1) * cpl
        first = np.linalg.norm(rings[a + 1] - rings[a], axis=1).mean()
        last = np.linalg.norm(rings[b] - rings[b - 1], axis=1).mean()
        return max(last / max(first, 1e-12), 1e-3)

    blocks, edges = [], []
    for L in range(N_LAYER):
        for b in range(N_CBLK):
            k0, k1 = b * q, (b + 1) * q
            blocks.append(
                f"    hex ({vid(L, k0, 0)} {vid(L + 1, k0, 0)} "
                f"{vid(L + 1, k1, 0)} {vid(L, k1, 0)} "
                f"{vid(L, k0, 1)} {vid(L + 1, k0, 1)} "
                f"{vid(L + 1, k1, 1)} {vid(L, k1, 1)}) "
                f"({cpl} {q} 1) simpleGrading ({layer_ratio(L):.6g} 1 1)")

    for level in range(nlv):
        for b in range(N_CBLK):
            k0, k1 = b * q, (b + 1) * q
            for z, zc in enumerate((0.0, Z_THICK)):
                pts = " ".join(
                    f"({lev[level][k % n][0]:.8f} {lev[level][k % n][1]:.8f} "
                    f"{zc:.6f})" for k in range(k0 + 1, k1))
                edges.append(f"    polyLine {vid(level, k0, z)} "
                             f"{vid(level, k1, z)} ({pts})")

    aero_faces, far_faces = [], []
    for b in range(N_CBLK):
        k0, k1 = b * q, (b + 1) * q
        aero_faces.append(f"            ({vid(0, k1, 0)} {vid(0, k0, 0)} "
                          f"{vid(0, k0, 1)} {vid(0, k1, 1)})")
        far_faces.append(f"            ({vid(nlv - 1, k0, 0)} "
                         f"{vid(nlv - 1, k1, 0)} {vid(nlv - 1, k1, 1)} "
                         f"{vid(nlv - 1, k0, 1)})")

    txt = (f"scale {CHORD_M};\n\nvertices\n(\n{vtxt}\n);\n\n"
           "blocks\n(\n" + "\n".join(blocks) + "\n);\n\n"
           "edges\n(\n" + "\n".join(edges) + "\n);\n\n"
           "defaultPatch\n{\n    name frontAndBack;\n    type empty;\n}\n\n"
           "boundary\n(\n"
           "    aerofoil { type wall; faces (\n"
           + "\n".join(aero_faces) + "\n    ); }\n"
           "    farField { type patch; faces (\n"
           + "\n".join(far_faces) + "\n    ); }\n"
           ");\n\nmergePatchPairs ();\n")
    head(os.path.join(case, "system", "blockMeshDict"), txt,
         "dictionary", "blockMeshDict")


