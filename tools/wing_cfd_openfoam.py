# Design point -- see module docstring.
CHORD_M = 0.093
U_INF = 34.1
NU_AIR = 1.48e-5          # m^2/s at 15 C
RHO_AIR = 1.225           # kg/m^3
# 2D extrusion depth, in CHORDS.  The dict is written normalised (chord = 1)
# and scaled to metres by `scale CHORD_M`, so nu and U stay SI.
Z_THICK = 0.1

# Mesh resolution.  N_CIRC must be divisible by 4 (one quarter per block).
N_CIRC = 400
N_RAD = 120
R_FAR = 20.0              # far field, in chords
N_LAYER = 12              # radial block layers (N_RAD must divide by this)
# Circumferential blocks.  blockMesh validates a block from its 8 CORNER
# vertices, not from its polyLine edges, so a block spanning a large arc of a
# curved aerofoil is judged on a chord that cuts through the section and is
# rejected as inside-out.  Keeping each block short makes the corner quad a
# good stand-in for the real curve (verified 2026-08-16: 4 blocks fail, 20 pass).
# It must also be large enough that a block's straight corner edge does not
# sag further into the section than the first layer is thick: sagitta ~ arc^2/8R,
# so a 0.1-chord arc sags ~1.2e-3 while layer 0 is only ~1.5e-3 thick -- nearly
# degenerate.  100 blocks (4 points each) sag ~5e-5, comfortably clear.
N_CBLK = 100              # N_CIRC must divide by this
# Near-wall spacing.  9e-6 m targets y+ ~1 (wall-resolved) but gives a cell
# aspect ratio near 1000 against the ~0.1-chord circumferential spacing, which
# is what makes the marching ill-conditioned: it tangled 9-47 quads.  3e-4 m is
# wall-function scale (y+ ~30) and is the best-conditioned value found, at 2-3
# inverted.  Left at the wall-function value so the next attempt starts from
# the best known state; revisit once the generator itself is replaced.
FIRST_CELL = 3.0e-4       # m


