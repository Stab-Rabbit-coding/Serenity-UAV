def read_coeffs(case):
    """Last (Cl, Cd) from the forceCoeffs output."""
    base = os.path.join(case, "postProcessing", "forceCoeffs")
    if not os.path.isdir(base):
        return None
    times = sorted(os.listdir(base), key=lambda t: float(t))
    dat = os.path.join(base, times[-1], "coefficient.dat")
    if not os.path.exists(dat):
        dat = os.path.join(base, times[-1], "forceCoeffs.dat")
    if not os.path.exists(dat):
        return None
    cols, last = None, None
    for line in open(dat):
        if line.startswith("#"):
            if "Time" in line:
                cols = line.lstrip("#").split()
            continue
        if line.strip():
            last = line.split()
    if last is None or cols is None:
        return None
    try:
        return (float(last[cols.index("Cl")]), float(last[cols.index("Cd")]))
    except (ValueError, IndexError):
        return None


def run_variant(name, x, yu, yl, alphas, workdir, keep):
    """Mesh once, then solve at each angle.  Returns {alpha: (Cl, Cd)}."""
    loop = resample_closed(x, yu, yl, N_CIRC)
    results = {}
    for alpha in alphas:
        case = os.path.join(workdir, f"{name}_a{alpha:g}")
        if os.path.exists(case):
            shutil.rmtree(case)
        os.makedirs(case)
        write_case(case, alpha)
        write_blockmesh(case, loop)

        r = foam("blockMesh", case)
        if r.returncode != 0:
            print(f"    a={alpha:>4g}  blockMesh FAILED")
            tail = (r.stdout + r.stderr).strip().splitlines()[-4:]
            for t in tail:
                print(f"        {t}")
            return results
        chk = foam("checkMesh -constant", case)
        nonortho = re.search(r"Max non-orthogonality = ([\d.]+)", chk.stdout)
        r = foam("simpleFoam", case)
        got = read_coeffs(case)
        conv = "converged" if "SIMPLE solution converged" in r.stdout else "endTime"
        if got is None:
            print(f"    a={alpha:>4g}  no coefficients ({conv})")
        else:
            cl, cd = got
            results[alpha] = got
            print(f"    a={alpha:>4g}  Cl {cl:+7.4f}  Cd {cd:7.5f}  "
                  f"L/D {cl / cd:8.2f}  [{conv}"
                  + (f", nonOrtho {nonortho.group(1)}" if nonortho else "")
                  + "]")
        if not keep:
            shutil.rmtree(case, ignore_errors=True)
    return results


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--alpha", type=float, nargs="+", default=[0.0, 4.0, 8.0],
                    help="angles of attack, degrees")
    ap.add_argument("--station", type=float, default=45.15)
    ap.add_argument("--workdir", default=os.path.join(
        os.environ.get("TMPDIR", "/tmp"), "serenity_wing_cfd"))
    ap.add_argument("--keep", action="store_true",
                    help="keep the OpenFOAM case directories")
    args = ap.parse_args()

    if not os.path.exists(FOAM_BASHRC):
        sys.exit(f"OpenFOAM env not found at {FOAM_BASHRC}")

    src = open(WING_SCAD).read()
    upper = scad_points(src, "S1223_UPPER")
    lower = scad_points(src, "S1223_LOWER")
    c_tip = scad_scalar(src, "WING_CHORD_TIP")
    ts_tip = scad_scalar(src, "THICKNESS_SCALE_TIP")
    bore = scad_scalar(src, "SPAR_BORE_OD")

    from wing_airfoil_variants import camber_thickness
    from wing_spar_station_fit import MIN_WALL_MM
    _cam, thk0 = camber_thickness(upper, lower, args.station / c_tip)
    need = (bore + 2.0 * MIN_WALL_MM) / (thk0 * c_tip)

    print("S1223 tip-section CFD -- OpenFOAM v1912, simpleFoam / k-omega SST")
    print(f"  chord {CHORD_M} m, U {U_INF} m/s, Re "
          f"{U_INF * CHORD_M / NU_AIR:,.0f}")
    print(f"  mesh {N_CIRC} x {N_RAD} O-grid, far field {R_FAR:g} chords")
    print(f"  spar station {args.station:.2f} mm -> thickness scale "
          f"{need:.3f} needed\n")

    cases = [
        ("baseline", 1.0, "uniform"),
        ("asbuilt_uniform_1p25", ts_tip, "uniform"),
        ("uniform_needed", need, "uniform"),
        ("thickness_only", need, "thickness"),
    ]
    os.makedirs(args.workdir, exist_ok=True)
    table = {}
    for name, sc, mode in cases:
        print(f"  {name}  (scale {sc:.3f}, {mode})")
        x, yu, yl = variant(upper, lower, sc, mode)
        table[name] = run_variant(name, x, yu, yl, args.alpha,
                                  args.workdir, args.keep)

    print("\n  summary (Cl / L-over-D)")
    hdr = "  " + "variant".ljust(24) + "".join(
        f"a={a:g}".rjust(18) for a in args.alpha)
    print(hdr)
    for name, _sc, _m in cases:
        row = "  " + name.ljust(24)
        for a in args.alpha:
            got = table[name].get(a)
            row += (f"{got[0]:+.3f}/{got[0] / got[1]:.1f}".rjust(18)
                    if got else "--".rjust(18))
        print(row)


if __name__ == "__main__":
    main()
