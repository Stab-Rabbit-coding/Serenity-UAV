def _part(name):
    return trimesh.load(os.path.join(REPO, "airframe", "stls", "fuselage", "head", name))


def rail_solid(y0, y1):
    """Inverted U with inward lower lips: ceiling over the band, two walls,
    two lips under the band floor the sled rides on."""
    hw = BAND_W / 2
    parts = [
        box(-hw - RAIL_T, hw + RAIL_T, y0, y1, BAND_Z1, BAND_Z1 + RAIL_T),  # ceiling
        box(hw, hw + RAIL_T, y0, y1, BAND_Z0 - RAIL_T, BAND_Z1),  # port wall
        box(-hw - RAIL_T, -hw, y0, y1, BAND_Z0 - RAIL_T, BAND_Z1),  # stbd wall
        box(hw - RAIL_LIP, hw, y0, y1, BAND_Z0 - RAIL_T, BAND_Z0),  # port lip
        box(-hw, -hw + RAIL_LIP, y0, y1, BAND_Z0 - RAIL_T, BAND_Z0),  # stbd lip
    ]
    m = to_man(parts[0])
    for p in parts[1:]:
        m = m + to_man(p)
    return trimesh.Trimesh(*_mesh(m))


def saddle_solid(y):
    """Transverse frame from the head skin up to the rail underside: two legs
    outboard of the band, bridged under the lips.  Bonded to the skin (the
    skin contact is expected -- skin_seat)."""
    hw = BAND_W / 2 + RAIL_T
    z_top = BAND_Z0 - RAIL_T
    legs = []
    for sx in (-1, 1):
        x0, x1 = sorted((sx * (hw - 6.0), sx * hw))
        legs.append(box(x0, x1, y - SADDLE_T / 2, y + SADDLE_T / 2, 120.0, z_top))
    bridge = box(-hw, hw, y - SADDLE_T / 2, y + SADDLE_T / 2, z_top - 4.0, z_top)
    m = to_man(bridge)
    for p in legs:
        m = m + to_man(p)
    # trim to the inside of the head skin: keep only what lies within the
    # head's outer hull envelope; the caller reports the skin contact
    return trimesh.Trimesh(*_mesh(m))


def _mesh(m):
    mm = m.to_mesh()
    return np.asarray(mm.vert_properties)[:, :3], np.asarray(mm.tri_verts)


def los_cones(parts):
    out = {}
    for name, children, idx, fov in (("camera", parts["cam"], 0, CAM_FOV_DEG),
                                     ("ToF", parts["tof"], 0, TOF_FOV_DEG),
                                     ("laser", parts["las"], 0, LASER_FOV_DEG)):
        ap = children[idx]
        centre = ap.bounds.mean(axis=0) + FLAT_N * 2.0  # just outboard of the skin
        r0 = (ap.extents.max()) / 2
        out[name] = cone(centre, FLAT_N, fov, LOS_LEN, r0=r0)
    return out


def pitot_tube():
    return cyl("y", PITOT_X, PITOT_Z, -PITOT_FWD, 12.0, PITOT_TUBE_D / 2)


def band_check(head_m):
    """Sliding band from the stop to the door-side aft limit against every
    obstacle it passes: head shell + collar, cargo shell (post-merge) and the
    cargo envelopes other than the retired single-pack battery and cradle."""
    cs = clf.shell_after_merge(trimesh.load(clf.SHELL))
    cs = cs if not isinstance(cs, trimesh.Trimesh) else to_man(cs)
    CL = clf.layout_t5()
    for k, e in list(CL.items()):
        if e.get("mirror"):
            CL[k + " (stbd)"] = dict(e, solid=clf.mirror_x(e["solid"]))
    band = to_man(box(-BAND_W / 2, BAND_W / 2, STOP_Y, BAND_Y1, BAND_Z0, BAND_Z1))
    rows = [("head shell + collar", (band ^ head_m).volume()),
            ("cargo shell", (band ^ cs).volume())]
    for k, e in CL.items():
        if k in ("battery", "battery cradle"):
            continue
        rows.append((f"cargo: {k}", (band ^ to_man(e["solid"])).volume()))
    return rows


def report(write_scad=False):
    head_tm = trimesh.load(HEAD)
    head_m = to_man(head_tm) + to_man(trimesh.load(COLLAR))
    L, parts = layout()
    solids = {}
    for name, e in list(L.items()):
        solids[name] = e["solid"]
        if e.get("mirror"):
            twin = e["mirror"]
            solids[twin] = mirror_x(e["solid"])
            L[twin] = dict(e, solid=solids[twin])
            L[twin].pop("mirror")
    print(f"head {os.path.relpath(HEAD, REPO)} + collar; aircraft datum R2")
    print(f"{'envelope':26s} {'hit mm3':>9s} {'<gap mm3':>9s}  note")
    fails = 0
    for name, tm in solids.items():
        e = L[name]
        m = to_man(tm)
        hit = (m ^ head_m).volume()
        gap = e.get("gap", GAP_MM)
        near = (to_man(dilate(tm, gap)) ^ head_m).volume() if gap > 0 else hit
        note = e.get("note", "")
        bad = False
        if name in REGISTERED:
            note = f"REGISTERED {REGISTERED[name]} (not counted)"
        elif e.get("skin_seat"):
            note = "bonded to skin (contact expected)"
        elif e.get("pocket"):
            # the pocket was cut from this exact solid: a residual > 5 mm^3
            # means the body no longer fits its pocket
            bad = hit > 5.0
            note = "fills its (already cut) pocket"
        else:
            bad = hit > 1.0 or near > 1.0
        if bad:
            fails += 1
            b = tm.bounds
            note += (f" FAIL X{b[0][0]:.0f}..{b[1][0]:.0f} Y{b[0][1]:.0f}..{b[1][1]:.0f}"
                     f" Z{b[0][2]:.0f}..{b[1][2]:.0f}")
        print(f"{name:26s} {hit:9.0f} {near:9.0f}  {note}")
    print("\npairwise interference (raw overlap mm3):")
    names = list(solids)
    over = 0
    for i, a in enumerate(names):
        for b_ in names[i + 1:]:
            if b_ in L[a].get("mates", ()) or a in L[b_].get("mates", ()):
                continue
            v = (to_man(solids[a]) ^ to_man(solids[b_])).volume()
            if v > 1.0:
                reg = REGISTERED.get(a) or REGISTERED.get(b_)
                over += 0 if reg else 1
                tag = f"REGISTERED {reg}" if reg else "OVERLAP"
                print(f"  {a:26s} x {b_:26s} {v:9.0f}  {tag}")
    if not over:
        print("  none")
    print("\nline of sight (outboard cones vs pitot tube):")
    tube = to_man(pitot_tube())
    los_bad = 0
    for k, c in los_cones(parts).items():
        v = (to_man(c) ^ tube).volume()
        los_bad += v > 0.5
        print(f"  {k:8s} cone x pitot tube {v:8.1f} mm3 {'BLOCKED' if v > 0.5 else 'clear'}")
    print(f"\nsliding band X+-{BAND_W / 2:.2f} Z{BAND_Z0:.2f}..{BAND_Z1:.2f}"
          f" Y{STOP_Y:.1f}..{BAND_Y1:.1f}:")
    band_bad = 0
    for k, v in band_check(head_m):
        if v > 0.5:
            band_bad += 1
            print(f"  {k:40s} {v:9.0f}  FOUL")
    if not band_bad:
        print("  clear of the head shell, collar, cargo shell and every cargo envelope")
    print(f"\nhead cell Y{CELL_Y0:.1f}..{CELL_Y1:.1f} (stop Y{STOP_Y:.1f}); second cell is in"
          " the middle/rear sections (docs/plans/2026-10-27-001-feat-middle-rear-layout-plan.md)")
    ok = not (fails or over or los_bad or band_bad)
    print(f"\nRESULT: {'PASS' if ok else 'FAIL'} ({fails} shell, {over} pair, "
          f"{los_bad} line-of-sight, {band_bad} band)")
    if write_scad:
        write_params()
    return ok


