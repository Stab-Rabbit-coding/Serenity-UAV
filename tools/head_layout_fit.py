def trapezoid_prism(y0, length, w0, w1, z0, z1):
    """Prism with a trapezoid plan (X width w0 at y0, w1 at y0+length)."""
    pts = np.array([[-w0 / 2, y0], [w0 / 2, y0], [w1 / 2, y0 + length], [-w1 / 2, y0 + length]])
    poly = trimesh.path.polygons.Polygon(pts)
    m = trimesh.creation.extrude_polygon(poly, z1 - z0)
    # extrude_polygon builds in (x, y) with height along +z
    m.apply_translation([X_CL, 0.0, z0])
    return m


def cone(apex, axis, full_deg, length, r0=0.0):
    """Frustum from apex (radius r0) along unit axis, half-angle full_deg/2."""
    r1 = r0 + length * np.tan(np.radians(full_deg / 2))
    c = trimesh.creation.cylinder(radius=1.0, height=length, sections=48)
    v = c.vertices.copy()
    t = (v[:, 2] + length / 2) / length  # 0 at apex end
    rad = r0 + (r1 - r0) * t
    v[:, :2] *= rad[:, None]
    v[:, 2] += length / 2
    c.vertices = v
    z = np.array([0, 0, 1.0])
    a = np.asarray(axis, float) / np.linalg.norm(axis)
    c.apply_transform(trimesh.geometry.align_vectors(z, a))
    c.apply_translation(apex)
    return c


def aperture_hull(local_pos):
    return np.asarray(local_pos) + mhi.BAKE_T


def sensor_body(children, idx, rear_zone):
    """Pocket solid (already cut) extended by the rear connector zone."""
    body = children[idx]
    tail = body.copy()
    tail.apply_translation(-FLAT_N * rear_zone)
    return trimesh.util.concatenate([body, tail]).convex_hull


